#!/usr/bin/env python3
# Generate i18n_hu.c from translations/hu.tsv
#   python3 translations/make_table.py > i18n_hu.c
# The table is sorted by the English text (byte order) for bsearch().
import csv, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
rows = {}
with open(os.path.join(here, 'hu.tsv'), newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f, delimiter='\t'):
        en = r['english'].replace('\\n', '\n')
        hu = r['hungarian'].replace('\\n', '\n')
        if en == hu or not hu:
            continue
        # printf conversions must stay the same and in the same order
        spec = re.compile(r'%[-+ #0]*\d*(?:\.\d+)?(?:l|ll|h)?[diouxXcsfeEgGp%]')
        if spec.findall(en) != spec.findall(hu):
            sys.exit('format mismatch: %r / %r' % (en, hu))
        rows[en] = hu

def c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

print('/* i18n_hu.c: Hungarian translation of the user interface texts')
print('   Generated by translations/make_table.py from translations/hu.tsv;')
print('   edit hu.tsv and run the script again instead of changing this file')
print('')
print('   This program is free software; you can redistribute it and/or modify')
print('   it under the terms of the GNU General Public License as published by')
print('   the Free Software Foundation; either version 2 of the License, or')
print('   (at your option) any later version.')
print('*/')
print('')
print('#include "config.h"')
print('')
print('#include <stddef.h>')
print('')
print('#include "i18n.h"')
print('')
print('const i18n_entry i18n_hu_table[] = {')
for en in sorted(rows, key=lambda s: s.encode('utf-8')):
    print('  { %s,\n    %s },' % (c(en), c(rows[en])))
print('};')
print('')
print('const size_t i18n_hu_table_size =')
print('  sizeof( i18n_hu_table ) / sizeof( i18n_hu_table[0] );')
